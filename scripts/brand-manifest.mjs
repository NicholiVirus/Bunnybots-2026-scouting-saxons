#!/usr/bin/env node
/**
 * Detects the launch logo in public/brand/ (by file extension) and writes
 * src/generated/brand.json for the splash screen + header. Runs before every
 * dev/build, so dropping a new logo file in public/brand/ is all you need.
 *
 * If several logo.* files exist, the first match in this order wins:
 *   logo.json (Lottie) → logo.webm → logo.mp4 → logo.gif → logo.png → logo.svg
 * For video/Lottie/GIF logos, put a still image next to it (logo-still.png or
 * logo-still.svg) — it is used for the header, PWA icons and reduced-motion.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brandDir = path.join(root, 'public', 'brand');
const order = [
  ['logo.json', 'lottie'],
  ['logo.webm', 'video'],
  ['logo.mp4', 'video'],
  ['logo.gif', 'gif'],
  ['logo.png', 'png'],
  ['logo.svg', 'svg'],
];
const files = existsSync(brandDir) ? readdirSync(brandDir) : [];
const hit = order.find(([f]) => files.includes(f));
const stillName = ['logo-still.png', 'logo-still.svg', 'logo.png', 'logo.svg', 'logo.gif'].find((f) => files.includes(f));

let brand;
if (!hit) {
  brand = { file: null, type: null, still: null, version: '0', splash: [] };
} else {
  const [file, type] = hit;
  const buf = readFileSync(path.join(brandDir, file));
  brand = {
    file: `/brand/${file}`,
    type,
    // animated logos (Lottie, video, GIF) use logo-still.* for the header, icons and reduced motion
    still: type === 'lottie' || type === 'video' || type === 'gif' ? (stillName ? `/brand/${stillName}` : '/icons/icon-512.png') : `/brand/${file}`,
    version: createHash('sha1').update(buf).digest('hex').slice(0, 10),
    splash: [],
  };
}

// iOS startup images generated by `npm run brand` (optional)
const splashDir = path.join(root, 'public', 'icons', 'splash');
if (existsSync(splashDir)) {
  const re = /^splash-(\d+)x(\d+)@(\d)x\.png$/;
  brand.splash = readdirSync(splashDir)
    .map((f) => {
      const m = re.exec(f);
      return m ? { url: `/icons/splash/${f}`, w: Number(m[1]), h: Number(m[2]), dpr: Number(m[3]) } : null;
    })
    .filter(Boolean);
}

mkdirSync(path.join(root, 'src', 'generated'), { recursive: true });
writeFileSync(path.join(root, 'src', 'generated', 'brand.json'), JSON.stringify(brand, null, 2) + '\n');

// Minimal manifest if `npm run brand` has never been run
const manifestPath = path.join(root, 'public', 'manifest.webmanifest');
if (!existsSync(manifestPath)) {
  writeFileSync(
    manifestPath,
    JSON.stringify(
      {
        name: 'Harvest Havoc Scouting — Saxon Robotics 611 · 526',
        short_name: 'Saxon Scout',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        background_color: '#06261f',
        theme_color: '#06261f',
        icons: [{ src: brand.still ?? '/brand/logo.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
      },
      null,
      2,
    ) + '\n',
  );
}
console.log(`brand: ${brand.file ?? 'none'} (${brand.type ?? '-'}), still ${brand.still ?? '-'}, ${brand.splash.length} iOS splash images`);
