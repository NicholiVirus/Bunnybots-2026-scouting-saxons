#!/usr/bin/env node
/**
 * Post-build: writes out/sw.js — a service worker that precaches EVERY file of
 * the static export, so the installed app opens and runs with zero connectivity
 * (event rule E6 bans hotspots). Data always comes from IndexedDB; the network
 * is only used for Supabase + The Bunnybots Alliance API (never cached here).
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'out');

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const skip = (rel) =>
  rel === 'sw.js' ||
  rel.endsWith('.map') ||
  rel.endsWith('.txt') || // RSC payloads are not needed for a static SPA-style export
  rel.startsWith('icons/splash/') || // iOS-only launch images, fetched by the OS
  rel === '404.html' ||
  rel === '_headers' || // Cloudflare config files are not served
  rel === '_redirects';

const files = walk(outDir)
  .map((p) => path.relative(outDir, p).split(path.sep).join('/'))
  .filter((rel) => !skip(rel));

const entries = files.map((rel) => {
  const hash = createHash('sha1').update(readFileSync(path.join(outDir, rel))).digest('hex').slice(0, 12);
  // trailingSlash export: "teams/index.html" is requested as "/teams/"
  let url = '/' + rel;
  if (rel === 'index.html') url = '/';
  else if (rel.endsWith('/index.html')) url = '/' + rel.slice(0, -'index.html'.length);
  return { url, hash };
});

const version = createHash('sha1').update(entries.map((e) => e.url + e.hash).join('|')).digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/build-sw.mjs — do not edit. Build ${version} */
const VERSION = ${JSON.stringify(version)};
const STATIC = 'hh-static-' + VERSION;
const PHOTOS = 'hh-photos';
const PRECACHE = ${JSON.stringify(entries.map((e) => e.url))};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(STATIC);
    // small batches: fail-soft on a flaky network, retry on next install
    for (let i = 0; i < PRECACHE.length; i += 20) {
      await cache.addAll(PRECACHE.slice(i, i + 20).map((u) => new Request(u, { cache: 'reload' })));
    }
    // first install activates immediately; updates wait for the user's "Update now"
    if (!self.registration.active) self.skipWaiting();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    const statics = keys.filter((k) => k.startsWith('hh-static-') && k !== STATIC);
    // keep exactly one previous build so pages opened just before the update still load
    statics.sort();
    for (const k of statics.slice(0, Math.max(0, statics.length - 1))) await caches.delete(k);
    await self.clients.claim();
  })());
});

async function fromCaches(request, opts) {
  const own = await caches.open(STATIC);
  const hit = await own.match(request, opts);
  if (hit) return hit;
  return caches.match(request, opts);
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Robot photos from Supabase Storage: cache-first (they must show offline)
  if (url.pathname.includes('/storage/v1/object/public/')) {
    event.respondWith((async () => {
      const cache = await caches.open(PHOTOS);
      const hit = await cache.match(req);
      if (hit) return hit;
      try {
        const res = await fetch(req);
        if (res.ok) cache.put(req, res.clone());
        return res;
      } catch (e) {
        return new Response('', { status: 504 });
      }
    })());
    return;
  }

  if (url.origin !== self.location.origin) return; // Supabase / results API: network only

  // App pages: cache first (instant + offline), query string ignored (/team/?id=611 → /team/)
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      const hit = await fromCaches(req, { ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch (e) {
        return (await fromCaches('/', {})) || new Response('Offline', { status: 503 });
      }
    })());
    return;
  }

  // Static assets: cache first, then network (and remember it)
  event.respondWith((async () => {
    const hit = await fromCaches(req, { ignoreSearch: url.pathname.startsWith('/brand/') });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && (url.pathname.startsWith('/_next/') || url.pathname.startsWith('/brand/') || url.pathname.startsWith('/icons/'))) {
        const cache = await caches.open(STATIC);
        cache.put(req, res.clone());
      }
      return res;
    } catch (e) {
      return new Response('', { status: 504 });
    }
  })());
});
`;

writeFileSync(path.join(outDir, 'sw.js'), sw);
console.log(`sw.js: precaching ${entries.length} files (build ${version})`);
