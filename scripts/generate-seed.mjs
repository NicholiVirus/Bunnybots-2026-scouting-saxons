#!/usr/bin/env node
/**
 * Generates supabase/seed.sql (28-team roster, alias map, default settings)
 * from src/config/event.ts + src/config/defaults.ts, and supabase/setup.sql
 * (migration + seed in ONE file to paste into the Supabase SQL Editor).
 *
 *   npm run seed:sql
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { ROSTER, DEFAULT_ALIASES, OUR_TEAMS } = await import(pathToFileURL(path.join(root, 'src/config/event.ts')).href);
const { DEFAULT_SETTINGS } = await import(pathToFileURL(path.join(root, 'src/config/defaults.ts')).href);

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const num = (id) => Number(String(id).replace(/\D/g, ''));

const lines = [];
lines.push('-- Generated by `npm run seed:sql` from src/config/event.ts — do not edit by hand.');
lines.push('-- Safe to re-run: existing rows (admin edits) are kept.');
lines.push('');
lines.push('insert into public.teams (id, number, name, status, notes) values');
lines.push(
  ROSTER.map((t) => `  (${q(t.id)}, ${num(t.id)}, ${q(t.name)}, ${q(t.status)}, ${q(t.notes ?? null)})`).join(',\n') +
    '\non conflict (id) do nothing;',
);
lines.push('');
lines.push('insert into public.team_aliases (alias, team_id) values');
lines.push(
  Object.entries(DEFAULT_ALIASES)
    .map(([a, t]) => `  (${q(a)}, ${q(t)})`)
    .join(',\n') + '\non conflict (alias) do nothing;',
);
lines.push('');
const settings = {
  tba_url: '',
  data_mode: 'live',
  poll_interval_sec: DEFAULT_SETTINGS.pollIntervalSec,
  alliance_count: DEFAULT_SETTINGS.allianceCount,
  cycle_outlier_cap_sec: DEFAULT_SETTINGS.cycleOutlierCapSec,
  cycle_burst_window_sec: DEFAULT_SETTINGS.cycleBurstWindowSec,
  picklist_auto_lock: DEFAULT_SETTINGS.picklistAutoLock,
  public_board: { enabled: false, token: '' },
  branding: null,
  splash_enabled: true,
};
lines.push('insert into public.settings (key, value) values');
lines.push(
  Object.entries(settings)
    .map(([k, v]) => `  (${q(k)}, ${j(v)})`)
    .join(',\n') + '\non conflict (key) do nothing;',
);
lines.push('');
lines.push('insert into public.picklist_meta (picking_team, locked) values');
lines.push(OUR_TEAMS.map((t) => `  (${q(t)}, false)`).join(',\n') + '\non conflict (picking_team) do nothing;');
lines.push('');

const seed = lines.join('\n');
writeFileSync(path.join(root, 'supabase/seed.sql'), seed);
const migDir = path.join(root, 'supabase/migrations');
const migFiles = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort();
const migration = migFiles.map((f) => readFileSync(path.join(migDir, f), 'utf8')).join('\n\n');
writeFileSync(
  path.join(root, 'supabase/setup.sql'),
  `-- ONE-PASTE SETUP: paste this whole file into Supabase → SQL Editor → Run.\n-- (= ${migFiles.map((f) => `migrations/${f}`).join(' + ')} + seed.sql, generated by \`npm run seed:sql\`)\n\n${migration}\n\n${seed}`,
);
console.log(`seed.sql: ${ROSTER.length} teams, ${Object.keys(DEFAULT_ALIASES).length} aliases; setup.sql written.`);
